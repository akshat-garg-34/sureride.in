// Generates src/data/*.ts from the Claude Design export.
// Source of truth: design/SureRide Website.dc.html  →  design/data.json
import fs from 'node:fs';
import path from 'node:path';
import { vehicles, cardSeats } from './fleet.config.mjs';
import { reviewsByRoute, homeReviews } from './reviews.config.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const HTML = path.join(ROOT, 'design', 'SureRide Website.dc.html');
const DATA = path.join(ROOT, 'design', 'data.json');
const OUT = path.join(ROOT, 'src', 'data');

const d = JSON.parse(fs.readFileSync(DATA, 'utf8'));
const html = fs.readFileSync(HTML, 'utf8');

const slugify = (t) =>
  t.replace(/→/g, ' to ')
   .replace(/&/g, ' and ')
   .toLowerCase()
   .replace(/[^a-z0-9]+/g, '-')
   .replace(/^-|-$/g, '');

const decode = (s) =>
  s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
   .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ').trim();

// Pull the "About the drive" prose out of the 1b artboard (it is static markup, not data).
function proseFromArtboard(id, heading) {
  const start = html.indexOf(`id="${id}"`);
  if (start === -1) return [];
  const scope = html.slice(start, start + 20000);
  const hIdx = scope.indexOf(`>${heading}</h2>`);
  if (hIdx === -1) return [];
  const after = scope.slice(hIdx, scope.indexOf('<h2', hIdx + 10));
  return [...after.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)]
    .map((m) => decode(m[1].replace(/<[^>]+>/g, '')))
    .filter((t) => t.length > 40)
    .map((text) => ({ text }));
}

const rupees = (s) => Number(String(s).replace(/[^\d]/g, '')) || 0;
/** Round to the nearest ₹100 and format Indian-style: ₹11,500. */
const fmt = (n) => '₹' + (Math.round(n / 100) * 100).toLocaleString('en-IN');

/**
 * Route fare tables are DERIVED, not stored: each vehicle's fareIndex is applied
 * to that route's Swift Dzire base price from the design export. One edit in
 * fleet.config.mjs re-prices every route page consistently.
 */
function faresForRoute(designFares) {
  const base = designFares.find((f) => /dzire/i.test(f.veh)) ?? designFares[0];
  const oneBase = rupees(base.one);
  const roundBase = rupees(base.round);
  return vehicles.flatMap((v) =>
    (v.rateVariants ?? [{ name: v.name, fareIndex: v.fareIndex }]).map((rate) => ({
      veh: rate.name,
      seats: rate.seatLabel ?? v.seatLabel,
      one: fmt(oneBase * rate.fareIndex),
      round: fmt(roundBase * rate.fareIndex),
    })),
  );
}

/** Plain "Innova" is no longer in the fleet — the Crysta replaced it. */
const fixVehicleNames = (t) =>
  typeof t === 'string' ? t.replace(/\bInnova\b(?!\s+(?:Crysta|Hycross))/g, 'Innova Crysta') : t;

const cleanText = (t) => typeof t === 'string' ? fixVehicleNames(decode(t)) : t;

// Route #1 lives in the top-level fields; the other seven are in routePages.
const primary = {
  label: 'Jaipur → Delhi',
  crumb: 'Jaipur to Delhi',
  h1: 'Jaipur to Delhi Taxi',
  sub: '280 km · about 5–6 hours via NH-48 · one-way and round trip',
  photoLabel: 'real fleet photo — Innova on NH-48',
  bookHeading: 'Book Jaipur → Delhi',
  callLabel: 'Call — Jaipur to Delhi',
  waLabel: 'WhatsApp "Jaipur to Delhi"',
  driveHeading: 'About the drive',
  stopsHeading: 'Popular stops on this route',
  fares: d.fareRows,
  prose: proseFromArtboard('1b', 'About the drive'),
  stops: d.stops,
  faqs: d.faqs,
  reviews: d.routeReviews,
  related: d.related,
};

const all = [primary, ...d.routePages].map((r) => ({
  slug: slugify(cleanText(r.label)),
  label: cleanText(r.label),
  crumb: cleanText(r.crumb),
  h1: cleanText(r.h1),
  sub: cleanText(r.sub),
  photoLabel: cleanText(r.photoLabel),
  bookHeading: cleanText(r.bookHeading),
  callLabel: cleanText(r.callLabel),
  waLabel: cleanText(r.waLabel),
  driveHeading: cleanText(r.driveHeading),
  stopsHeading: cleanText(r.stopsHeading),
  fares: faresForRoute(r.fares),
  prose: r.prose,
  stops: r.stops.map((s) => ({ ...s, slug: slugify(s.name) })),
  faqs: r.faqs.map((f) => ({ q: cleanText(f.q), a: cleanText(f.a) })),
  // Design-export reviews were invented. Real ones only, from reviews.config.mjs.
  reviews: reviewsByRoute[r.slug] ?? [],
  related: r.related,
}));

const known = new Set(all.map((r) => r.slug));
// Home-card summary (km / from-price) keyed by label.
const summary = Object.fromEntries(d.routes.map((r) => [r.title, r]));

for (const r of all) {
  const s = summary[r.label];
  r.km = s?.km ?? r.sub.split('·')[0].trim();
  r.fromPrice = s?.price ?? r.fares?.[0]?.one ?? '';
  r.related = r.related.map((x) => {
    const slug = slugify(x.title);
    return { ...x, slug, exists: known.has(slug) };
  });
}

const banner = `// GENERATED by scripts/generate-data.mjs from the Claude Design export.
// Edit design/ and re-run \`npm run gen\`, or edit here and stop regenerating.
`;

const w = (file, body) => {
  fs.writeFileSync(path.join(OUT, file), banner + body);
  console.log('wrote', file);
};

const j = (v) => JSON.stringify(v, null, 2);

w('routes.ts', `
export type Fare = { veh: string; seats: string; one: string; round: string };
export type Stop = { name: string; slug: string; km: string; note: string };
export type Faq = { q: string; a: string };
export type Review = { text: string; name: string; meta: string };
export type Related = { title: string; km: string; slug: string; exists: boolean };

export type Route = {
  slug: string;
  label: string;
  crumb: string;
  h1: string;
  sub: string;
  km: string;
  fromPrice: string;
  photoLabel: string;
  bookHeading: string;
  callLabel: string;
  waLabel: string;
  driveHeading: string;
  stopsHeading: string;
  fares: Fare[];
  prose: { text: string }[];
  stops: Stop[];
  faqs: Faq[];
  reviews: Review[];
  related: Related[];
};

export const routes: Route[] = ${j(all)};

export const routeBySlug = (slug: string) => routes.find((r) => r.slug === slug);
`);

w('vehicles.ts', `
export type Vehicle = {
  slug: string; photo: string; name: string; seats: number; seatLabel: string; seatLong: string;
  bags: string; regularPerKm: string; offerPerKm: string;
  fareIndex: number; best: string; note: string;
  rateVariants?: { name: string; seatLabel?: string; regularPerKm: string; offerPerKm: string; fareIndex: number }[];
};

/** Source: scripts/fleet.config.mjs — client-supplied, not from the design export. */
export const vehicles: Vehicle[] = ${j(vehicles)};
`);

w('fleet.ts', `
export type FleetCard = { name: string; photo: string; seats: string; note: string };
export type VehicleRate = { name: string; regularPerKm: string; offerPerKm: string };
export type FleetDetail = { name: string; photo: string; seats: string; bags: string; rates: VehicleRate[]; best: string; note: string };

export const fleetCards: FleetCard[] = ${j(vehicles.map((v) => ({ name: v.name, photo: v.photo, seats: cardSeats(v), note: v.best.split('.')[0] + '.' })))};

export const fleetDetail: FleetDetail[] = ${j(vehicles.map((v) => ({
  name: v.name,
  photo: v.photo,
  seats: v.seatLong,
  bags: v.bags,
  rates: (v.rateVariants ?? [{ name: v.name, regularPerKm: v.regularPerKm, offerPerKm: v.offerPerKm }])
    .map(({ name, regularPerKm, offerPerKm }) => ({ name, regularPerKm, offerPerKm })),
  best: v.best,
  note: v.note,
})))};
`);

w('fares.ts', `
export type RateRow = { veh: string; seats: string; regularPerKm: string; offerPerKm: string };
export type Charge = { title: string; when: string; body: string; hi: string };

export const rateRows: RateRow[] = ${j(vehicles.flatMap((v) =>
  (v.rateVariants ?? [{ name: v.name, regularPerKm: v.regularPerKm, offerPerKm: v.offerPerKm }])
    .map(({ name, seatLabel, regularPerKm, offerPerKm }) => ({ veh: name, seats: seatLabel ?? v.seatLabel, regularPerKm, offerPerKm })),
))};
export const charges: Charge[] = ${j(d.charges)};
`);

w('home.ts', `
export type Service = { title: string; note: string };
export type Pilgrim = { hi: string; en: string; km: string };
export type Review = { text: string; name: string; meta: string };

export const services: Service[] = ${j(
  d.services.map((x) => {
    // Client-confirmed detail overrides on top of the design copy.
    if (/tempo/i.test(x.title)) return { ...x, note: '8, 12, 17 and 20 seater, Force and Urbania.' };
    if (/airport/i.test(x.title))
      return { ...x, note: 'Share the flight and terminal details when booking so the pickup can be planned clearly.' };
    if (/one-way/i.test(x.title))
      return { ...x, note: 'Request a written quote for the one-way route, vehicle and applicable charges.' };
    if (/round trip/i.test(x.title))
      return { ...x, note: 'Confirm the return plan, waiting requirements and vehicle availability in writing.' };
    if (/local 8hr/i.test(x.title))
      return { ...x, title: 'Local booking', note: 'Share the hours, stops and distance so the local package can be quoted accurately.' };
    return x;
  }),
)};
export const pilgrimage: Pilgrim[] = ${j(d.pilgrim)};
export const reviews: Review[] = ${j(homeReviews)};
`);

console.log(`\n${all.length} routes: ${all.map((r) => r.slug).join(', ')}`);
console.log(`primary prose paragraphs: ${primary.prose.length}`);
console.log(`fleet: ${vehicles.length} vehicles — ${vehicles.map((v) => v.name).join(', ')}`);
console.log('sample fares (jaipur-to-delhi):', all[0].fares.map((f) => `${f.veh} ${f.one}/${f.round}`).join(' · '));
