// Pre-generates AVIF and WebP variants for everything in public/photos, and
// writes a manifest so components know which images actually exist.
//
// `output: "export"` means next/image cannot optimise at request time, so the
// work happens here instead: three widths per image in two modern formats,
// with the original JPEG kept as the last-resort fallback.
//
//   npm run images
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const PHOTOS = path.join(ROOT, 'public/photos');
const MIN_WIDTH = 240;

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : /\.jpe?g$/i.test(e.name) ? [p] : [];
  });

const manifest = {};
let written = 0;
let skipped = 0;

for (const file of walk(PHOTOS).sort()) {
  const rel = path.relative(path.join(ROOT, 'public'), file).replace(/\\/g, '/');
  const key = rel.replace(/\.jpe?g$/i, '');
  const meta = await sharp(file).metadata();

  const widths = [...new Set([Math.round(meta.width / 3), Math.round(meta.width / 2), meta.width])]
    .filter((w) => w >= MIN_WIDTH)
    .sort((a, b) => a - b);

  for (const w of widths) {
    for (const [ext, opts] of [
      ['avif', { quality: 50, effort: 4 }],
      ['webp', { quality: 78 }],
    ]) {
      const out = path.join(ROOT, 'public', `${key}-${w}.${ext}`);
      if (fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(file).mtimeMs) {
        skipped++;
        continue;
      }
      await sharp(file).resize({ width: w, withoutEnlargement: true })[ext](opts).toFile(out);
      written++;
    }
  }

  manifest[key] = { w: meta.width, h: meta.height, widths };
}

const out = `// GENERATED by scripts/optimize-images.mjs — do not edit.
// Components look images up here, so a photo that has not been supplied yet
// falls back to the placeholder instead of shipping a broken <img>.

export type ImageEntry = { w: number; h: number; widths: number[] };

export const images: Record<string, ImageEntry> = ${JSON.stringify(manifest, null, 2)};

export const hasImage = (src?: string): src is string => !!src && src in images;
`;
fs.writeFileSync(path.join(ROOT, 'src/data/images.ts'), out);

const bytes = (glob) =>
  walk(PHOTOS).length &&
  fs
    .readdirSync(PHOTOS, { recursive: true })
    .filter((f) => typeof f === 'string' && f.endsWith(glob))
    .reduce((a, f) => a + fs.statSync(path.join(PHOTOS, f)).size, 0);

console.log(`${Object.keys(manifest).length} source images`);
console.log(`${written} variants written, ${skipped} up to date`);
console.log(`jpeg ${(bytes('.jpg') / 1e6).toFixed(1)}MB · webp ${(bytes('.webp') / 1e6).toFixed(1)}MB · avif ${(bytes('.avif') / 1e6).toFixed(1)}MB`);
